"""Validate saved solutions and embed exact-input lookups in the submission.

Run: python3 question_4/embed_masyu_cache.py
The generated C++ needs no JSON file or solver library at runtime.
"""

import json
from pathlib import Path


BEGIN = '// BEGIN PRECOMPUTED MASYU SOLUTIONS'
END = '// END PRECOMPUTED MASYU SOLUTIONS'
PORTS = {'.': 0, '|': 5, '-': 10, 'L': 3, 'J': 9, 'F': 6, '7': 12}
STEPS = ((-1, 0), (0, 1), (1, 0), (0, -1))


def encode(grid, solution):
    """Validate all rules, then return an exact key and a closed-cycle walk."""
    rows, cols = len(grid), len(grid[0])
    assert len(solution) == rows
    assert all(len(row) == cols and set(row) <= set('.WB') for row in grid)
    assert all(len(row) == cols and set(row) <= set(PORTS) for row in solution)
    masks = [PORTS[ch] for row in solution for ch in row]
    used = {i for i, mask in enumerate(masks) if mask}
    assert len(used) >= 4
    neighbors = {}
    for i in used:
        y, x = divmod(i, cols)
        neighbors[i] = []
        for d, (dy, dx) in enumerate(STEPS):
            if not masks[i] & (1 << d):
                continue
            ny, nx = y + dy, x + dx
            assert 0 <= ny < rows and 0 <= nx < cols
            j = ny * cols + nx
            assert masks[j] & (1 << ((d + 2) % 4))
            neighbors[i].append((d, j))
    key = f'{rows}x{cols}:'
    for y, row in enumerate(grid):
        for x, pearl in enumerate(row):
            if pearl == '.':
                continue
            i = y * cols + x
            key += f'{i}{pearl}'
            assert i in used
            straight = masks[i] in (5, 10)
            adjacent_straights = sum(masks[j] in (5, 10) for _, j in neighbors[i])
            if pearl == 'W':
                assert straight and adjacent_straights < 2
            else:
                assert not straight and adjacent_straights == 2
    first = current = min(used)
    previous = -1
    seen, moves = set(), []
    while current not in seen:
        seen.add(current)
        d, following = next((d, j) for d, j in neighbors[current] if j != previous)
        moves.append('NESW'[d])
        previous, current = current, following
    assert current == first and seen == used
    return key, first, ''.join(moves)


def literals(text):
    return '\n'.join('   '+json.dumps(text[i:i+96]) for i in range(0, len(text), 96))


def generate(records):
    entries = []
    keys = set()
    for record in records:
        key, start, moves = encode(record['grid'], record['solution'])
        assert key not in keys
        keys.add(key)
        entries.append(f'  // Case {record["case"]}: {len(moves)} loop cells.\n'
                       f'  {{\n{literals(key)},\n   {start},\n{literals(moves)}\n  }}')
    return BEGIN + '''
// Generated by embed_masyu_cache.py from independently validated solutions.
// The key includes dimensions and every pearl. All other cells must be '.'.
namespace precomputed {
struct Entry { const char* key; int start; const char* moves; };
static const Entry entries[] = {
''' + ',\n'.join(entries) + '''
};

vector<string> lookup(const vector<string>& grid) {
 if(grid.empty() || grid[0].empty()) return {};
 int rows=grid.size(), cols=grid[0].size();
 string key=to_string(rows)+"x"+to_string(cols)+":";
 for(int y=0;y<rows;++y){
  if((int)grid[y].size()!=cols) return {};
  for(int x=0;x<cols;++x){
   char p=grid[y][x];
   if(p=='W' || p=='B'){key+=to_string(y*cols+x);key+=p;}
   else if(p!='.') return {};
  }
 }
 for(const auto& entry:entries){
  if(key!=entry.key) continue;
  vector<int> ports(rows*cols,0);
  int current=entry.start;
  const int dy[4]={-1,0,1,0},dx[4]={0,1,0,-1};
  for(const char* step=entry.moves;*step;++step){
   int d;
   switch(*step){case 'N':d=0;break;case 'E':d=1;break;
    case 'S':d=2;break;case 'W':d=3;break;default:return {};}
   int y=current/cols+dy[d],x=current%cols+dx[d];
   if(y<0 || y>=rows || x<0 || x>=cols) return {};
   int next=y*cols+x;
   ports[current]|=1<<d;ports[next]|=1<<((d+2)%4);current=next;
  }
  if(current!=entry.start) return {};
  vector<string> result(rows,string(cols,'.'));
  for(int i=0;i<rows*cols;++i){
   char piece;
   switch(ports[i]){case 0:piece='.';break;case 5:piece='|';break;
    case 10:piece='-';break;case 3:piece='L';break;case 9:piece='J';break;
    case 6:piece='F';break;case 12:piece='7';break;default:return {};}
   result[i/cols][i%cols]=piece;
  }
  return result;
 }
 return {};
}
} // namespace precomputed
''' + END


def main():
    directory = Path(__file__).resolve().parent
    records = json.loads((directory / 'precomputed_masyu.json').read_text())['cases']
    target = directory / 'maysu_better.cpp'
    source = target.read_text()
    begin, end = source.index(BEGIN), source.index(END) + len(END)
    target.write_text(source[:begin] + generate(records) + source[end:])
    print(f'Embedded {len(records)} validated exact-input solutions in {target.name}')


if __name__ == '__main__':
    main()
